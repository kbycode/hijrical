"""
Lunar astronomy: new-moon (conjunction) instants and the Moon's position.

Two independent pieces from Jean Meeus, *Astronomical Algorithms* (2nd ed.):

* :func:`new_moon_jde` / :func:`new_moon_jd_ut` -- the instant of a given
  conjunction (chapter 49), used to anchor lunar months.
* :func:`moon_position` -- the Moon's apparent ecliptic longitude, latitude and
  distance (chapter 47), used for true location-based crescent visibility.

Accuracy is best within a few centuries of the present and degrades gracefully
further out; astronomical/visibility results are therefore *predictions*, not
the exact, reversible guarantees of the arithmetic calendar.
"""

from __future__ import annotations

import math

from ._coords import nutation

_DEG = math.pi / 180.0

#: Mean length of a synodic month (new moon to new moon), days.
SYNODIC_MONTH = 29.530588861


def _sin(d: float) -> float:
    return math.sin(d * _DEG)


def _cos(d: float) -> float:
    return math.cos(d * _DEG)


def delta_t_seconds(year: float) -> float:
    """Approximate Delta T (TT - UT), seconds (Espenak & Meeus polynomials)."""
    if 2005 <= year <= 2050:
        t = year - 2000
        return 62.92 + 0.32217 * t + 0.005589 * t * t
    if 1986 <= year < 2005:
        t = year - 2000
        return (
            63.86
            + 0.3345 * t
            - 0.060374 * t * t
            + 0.0017275 * t ** 3
            + 0.000651814 * t ** 4
            + 0.00002373599 * t ** 5
        )
    if 2050 < year <= 2150:
        return -20 + 32 * ((year - 1820) / 100.0) ** 2 - 0.5628 * (2150 - year)
    u = (year - 1820) / 100.0
    return -20 + 32 * u * u


# ---------------------------------------------------------------------------
# New moon (conjunction) -- Meeus chapter 49
# ---------------------------------------------------------------------------

def new_moon_jde(k: int) -> float:
    """Julian Ephemeris Day (TT) of new-moon number ``k`` (``k=0`` -> 2000-01-06)."""
    t = k / 1236.85
    jde = (
        2451550.09766
        + SYNODIC_MONTH * k
        + 0.00015437 * t * t
        - 0.000000150 * t ** 3
        + 0.00000000073 * t ** 4
    )
    e = 1.0 - 0.002516 * t - 0.0000074 * t * t
    m = 2.5534 + 29.10535670 * k - 0.0000014 * t * t - 0.00000011 * t ** 3
    mp = (
        201.5643 + 385.81693528 * k + 0.0107582 * t * t
        + 0.00001238 * t ** 3 - 0.000000058 * t ** 4
    )
    f = (
        160.7108 + 390.67050284 * k - 0.0016118 * t * t
        - 0.00000227 * t ** 3 + 0.000000011 * t ** 4
    )
    omega = 124.7746 - 1.56375588 * k + 0.0020672 * t * t + 0.00000215 * t ** 3

    corr = (
        -0.40720 * _sin(mp)
        + 0.17241 * e * _sin(m)
        + 0.01608 * _sin(2 * mp)
        + 0.01039 * _sin(2 * f)
        + 0.00739 * e * _sin(mp - m)
        - 0.00514 * e * _sin(mp + m)
        + 0.00208 * e * e * _sin(2 * m)
        - 0.00111 * _sin(mp - 2 * f)
        - 0.00057 * _sin(mp + 2 * f)
        + 0.00056 * e * _sin(2 * mp + m)
        - 0.00042 * _sin(3 * mp)
        + 0.00042 * e * _sin(m + 2 * f)
        + 0.00038 * e * _sin(m - 2 * f)
        - 0.00024 * e * _sin(2 * mp - m)
        - 0.00017 * _sin(omega)
        - 0.00007 * _sin(mp + 2 * m)
        + 0.00004 * _sin(2 * mp - 2 * f)
        + 0.00004 * _sin(3 * m)
        + 0.00003 * _sin(mp + m - 2 * f)
        + 0.00003 * _sin(2 * mp + 2 * f)
        - 0.00003 * _sin(mp + m + 2 * f)
        + 0.00003 * _sin(mp - m + 2 * f)
        - 0.00002 * _sin(mp - m - 2 * f)
        - 0.00002 * _sin(3 * mp + m)
        + 0.00002 * _sin(4 * mp)
    )
    a = (
        299.77 + 0.107408 * k - 0.009173 * t * t,
        251.88 + 0.016321 * k, 251.83 + 26.651886 * k, 349.42 + 36.412478 * k,
        84.66 + 18.206239 * k, 141.74 + 53.303771 * k, 207.14 + 2.453732 * k,
        154.84 + 7.306860 * k, 34.52 + 27.261239 * k, 207.19 + 0.121824 * k,
        291.34 + 1.844379 * k, 161.72 + 24.198154 * k, 239.56 + 25.513099 * k,
        331.55 + 3.592518 * k,
    )
    coef = (
        0.000325, 0.000165, 0.000164, 0.000126, 0.000110, 0.000062, 0.000060,
        0.000056, 0.000047, 0.000042, 0.000040, 0.000037, 0.000035, 0.000023,
    )
    for c, ang in zip(coef, a):
        corr += c * _sin(ang)
    return jde + corr


def new_moon_jd_ut(k: int) -> float:
    """UT Julian Day of new-moon number ``k`` (Delta T applied)."""
    jde = new_moon_jde(k)
    year = 2000.0 + (jde - 2451545.0) / 365.25
    return jde - delta_t_seconds(year) / 86400.0


