def moon_position(jde: float) -> tuple[float, float, float]:
    """Apparent geocentric position of the Moon at ``jde`` (Julian Ephemeris Day, TT).

    Returns ``(apparent_longitude_deg, latitude_deg, distance_km)``.

    >>> lon, lat, dist = moon_position(2448724.5)  # Meeus example 47.a
    >>> round(lon, 3), round(lat, 3), round(dist, 1)
    (133.167, -3.229, 368409.7)
    """
    t = (jde - 2451545.0) / 36525.0
    lp = (
        218.3164477 + 481267.88123421 * t - 0.0015786 * t * t
        + t ** 3 / 538841.0 - t ** 4 / 65194000.0
    )
    d = (
        297.8501921 + 445267.1114034 * t - 0.0018819 * t * t
        + t ** 3 / 545868.0 - t ** 4 / 113065000.0
    )
    m = 357.5291092 + 35999.0502909 * t - 0.0001536 * t * t + t ** 3 / 24490000.0
    mp = (
        134.9633964 + 477198.8675055 * t + 0.0087414 * t * t
        + t ** 3 / 69699.0 - t ** 4 / 14712000.0
    )
    f = (
        93.2720950 + 483202.0175233 * t - 0.0036539 * t * t
        - t ** 3 / 3526000.0 + t ** 4 / 863310000.0
    )
    a1 = 119.75 + 131.849 * t
    a2 = 53.09 + 479264.290 * t
    a3 = 313.45 + 481266.484 * t
    e = 1.0 - 0.002516 * t - 0.0000074 * t * t

    sum_l = sum_r = 0.0
    for cd, cm, cmp, cf, cl, cr in _TERMS_LR:
        arg = cd * d + cm * m + cmp * mp + cf * f
        ecorr = e ** abs(cm)
        sum_l += cl * ecorr * _sin(arg)
        sum_r += cr * ecorr * _cos(arg)

    sum_b = 0.0
    for cd, cm, cmp, cf, cb in _TERMS_B:
        arg = cd * d + cm * m + cmp * mp + cf * f
        sum_b += cb * (e ** abs(cm)) * _sin(arg)

    # Additive (planetary / flattening) terms, Meeus p. 342.
    sum_l += 3958 * _sin(a1) + 1962 * _sin(lp - f) + 318 * _sin(a2)
    sum_b += (
        -2235 * _sin(lp) + 382 * _sin(a3) + 175 * _sin(a1 - f) + 175 * _sin(a1 + f)
        + 127 * _sin(lp - mp) - 115 * _sin(lp + mp)
    )

    lon = lp + sum_l / 1_000_000.0
    lat = sum_b / 1_000_000.0
    dist = 385000.56 + sum_r / 1000.0

    dpsi, _ = nutation(jde)
    lon = (lon + dpsi) % 360.0  # apparent longitude
    return lon, lat, dist
