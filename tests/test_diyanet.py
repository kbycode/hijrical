def _d(iso: str) -> date:
    y, m, dd = (int(p) for p in iso.split("-"))
    return date(y, m, dd)


def test_matches_every_official_row():
    """100% agreement with Diyanet across all published rows -- both directions."""
    cal = DiyanetCalendar()
    for hy, hm, hd, iso in OFFICIAL:
        h = HijriDate(hy, hm, hd, calendar=cal)
        assert h.to_gregorian() == _d(iso), f"{hy}-{hm:02d}-{hd:02d} -> {h.to_gregorian()} != {iso}"
        back = HijriDate.from_date(_d(iso), calendar=cal)
        assert (back.year, back.month, back.day) == (hy, hm, hd), f"{iso} -> {back}"


def test_table_is_contiguous_and_sane():
    cal = DiyanetCalendar()
    entries = list(DIYANET_MONTH_STARTS)
    for (y1, m1, _), (y2, m2, _) in zip(entries, entries[1:]):
        expected = (y1, m1 + 1) if m1 < 12 else (y1 + 1, 1)
        assert (y2, m2) == expected, f"gap between {y1}-{m1} and {y2}-{m2}"
    # Every fully covered month must be 29 or 30 days long.
    for y, m, _ in entries[:-1]:
        assert cal.month_length(y, m) in (29, 30), (y, m, cal.month_length(y, m))


def test_hijri_years_have_sane_length():
    cal = DiyanetCalendar()
    for year in (1444, 1445, 1446, 1447, 1448):
        total = sum(cal.month_length(year, m) for m in range(1, 13))
        assert total in (354, 355), (year, total)


def test_coverage_and_fallback():
    cal = DiyanetCalendar()
    first, last = cal.coverage()
    assert first == (1443, 6)
    assert last == (1449, 8)
    assert cal.is_official(1447, 9) is True
    assert cal.covers(1500, 1) is False
    # Outside the table it still answers, via the astronomical engine.
    far = HijriDate(1460, 9, 1, calendar=cal)
    assert far.to_gregorian().year > 2030
    assert cal.is_official(1460, 9) is False


def test_round_trip_across_whole_table():
    cal = DiyanetCalendar()
    start = HijriDate(1443, 6, 1, calendar=cal).jdn
    end = HijriDate(1449, 8, 1, calendar=cal).jdn
    for jdn in range(start, end):
        y, m, d = cal.from_jdn(jdn)
        assert cal.to_jdn(y, m, d) == jdn


def test_invalid_day_rejected():
    cal = DiyanetCalendar()
    # Ramadan 1447 has 29 days in Diyanet's calendar (19 Feb - 19 Mar 2026).
    assert cal.month_length(1447, 9) == 29
    assert_raises(Exception, HijriDate, 1447, 9, 30, calendar=cal)
